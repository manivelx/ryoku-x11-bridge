func captureProviderOutput(t *testing.T) (*bytes.Buffer, func()) {
	t.Helper()
	previous := out
	var buffer bytes.Buffer
	out = bufio.NewWriter(&buffer)
	return &buffer, func() {
		_ = out.Flush()
		out = previous
	}
}

func TestRequiredWindowID(t *testing.T) {
	if id, err := requiredWindowID([]string{"123"}, 0); err != nil || id != 123 {
		t.Fatalf("expected id 123, got %d, err=%v", id, err)
	}
	for _, value := range []string{"", "0", "-1", "abc"} {
		if _, err := requiredWindowID([]string{value}, 0); err == nil {
			t.Fatalf("expected invalid window id %q to fail", value)
		}
	}
}

func TestRunBindsReturnsLockedSessionBindings(t *testing.T) {
	buffer, restore := captureProviderOutput(t)
	defer restore()
	if err := runBinds(nil); err != nil {
		t.Fatal(err)
	}
	_ = out.Flush()
	var rows []bindRow
	if err := json.Unmarshal(buffer.Bytes(), &rows); err != nil {
		t.Fatal(err)
	}
	if len(rows) < 25 {
		t.Fatalf("expected base bindings and workspace family, got %d", len(rows))
	}
	for _, row := range rows {
		if row.ID == "" || row.Chord == "" || row.Rebindable || !row.Locked {
			t.Fatalf("invalid fixed i3 bind row: %+v", row)
		}
	}
}

func TestRunCapsAdvertisesOnlyImplementedFeatures(t *testing.T) {
	buffer, restore := captureProviderOutput(t)
	defer restore()
	if err := runCaps(); err != nil {
		t.Fatal(err)
	}
	_ = out.Flush()
	var caps Caps
	if err := json.Unmarshal(buffer.Bytes(), &caps); err != nil {
		t.Fatal(err)
	}
	if caps.Name != "i3" || caps.ConfigEntry != "ryoku-x11/config" || caps.ConfigDir != "ryoku-x11" {
		t.Fatalf("unexpected i3 provider metadata: %+v", caps)
	}
	expected := map[string]bool{
		"workspaces": true, "workspaceMoveToOutput": true, "windowWorkspaceMap": true,
		"workspaceFullscreenState": true, "windowGeometry": true, "windowFloat": true,
		"sessionExit": true, "configReload": true, "tiledLayout": true,
	}
	for _, capability := range caps.Supports {
		if !expected[capability] {
			t.Fatalf("provider advertises unimplemented capability %q", capability)
		}
		delete(expected, capability)
	}
	for capability := range expected {
		t.Fatalf("provider does not advertise implemented capability %q", capability)
	}
}

func TestApplyPreviewIsSideEffectFree(t *testing.T) {
	configHome := t.TempDir()
	t.Setenv("XDG_CONFIG_HOME", configHome)
	store := filepath.Join(t.TempDir(), "store.json")
	if err := os.WriteFile(store, []byte("{}"), 0o600); err != nil {
		t.Fatal(err)
	}
	buffer, restore := captureProviderOutput(t)
	defer restore()
	if err := runApply([]string{store, "--preview"}); err != nil {
		t.Fatal(err)
	}
	_ = out.Flush()
	if _, err := os.Stat(filepath.Join(configHome, "ryoku-x11", "generated.conf")); !os.IsNotExist(err) {
		t.Fatalf("preview must not write generated config, stat err=%v", err)
	}
	if !strings.Contains(buffer.String(), "desktop.keybinds") {
		t.Fatalf("expected unhonored settings in apply report: %s", buffer.String())
	}
}

func TestApplyWritesOnlyGeneratedConfig(t *testing.T) {
	configHome := t.TempDir()
	t.Setenv("XDG_CONFIG_HOME", configHome)
	store := filepath.Join(t.TempDir(), "store.json")
	if err := os.WriteFile(store, []byte("{}"), 0o600); err != nil {
		t.Fatal(err)
	}
	buffer, restore := captureProviderOutput(t)
	defer restore()
	if err := runApply([]string{store}); err != nil {
		t.Fatal(err)
	}
	_ = out.Flush()
	generated := filepath.Join(configHome, "ryoku-x11", "generated.conf")
	content, err := os.ReadFile(generated)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(content), "Generated by ryoku-wm-i3") {
		t.Fatalf("unexpected generated config: %s", content)
	}
	if !strings.Contains(buffer.String(), "ryoku-x11/generated.conf") {
		t.Fatalf("apply report must list the generated file: %s", buffer.String())
	}
}
